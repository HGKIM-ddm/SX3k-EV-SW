/***********************************************************************************************************************
 * File Name    : Drv8434a.h
 * Device(s)    : TI DRV8434A-Q1 (VQFN RGE 24)
 * MCU          : Renesas RH850/F1KM-S1 (R7F701695)
 * Description  : DRV8434A-Q1 스테퍼 드라이버 저수준 제어 계층 (GPIO / 상태 / 모드)
 *
 *  ┌─ 설계 원칙 ────────────────────────────────────────────────────────────────┐
 *  │ 1. 이 계층은 '핀 조작'과 '모드 설정'만 담당한다.                             │
 *  │    스톨 판정, 진단 시퀀스, 위치 로직은 상위 계층(Service/Safety)의 몫.        │
 *  │ 2. 블로킹 대기를 넣지 않는다. 필요한 지연은 상수로 노출하고                   │
 *  │    호출자(상태머신)가 타이머로 처리한다.                                     │
 *  │    예외: FaultClear 의 nSLEEP 펄스(20~40us)만 블로킹.                       │
 *  │ 3. 동작이 다른 것은 함수를 분리한다. 인자로 분기하지 않는다.                  │
 *  └───────────────────────────────────────────────────────────────────────────┘
 *
 *  ┌─ 핀 매핑 (SX3K_EV 신규보드) ───────────────────────────────────────────────┐
 *  │ 드라이버핀  MCU포트   비트   레벨종류      비고                              │
 *  │ ENABLE      P10       0     Tri-level    Low=차단 / High=동작 / Hi-Z=8배    │
 *  │ nSLEEP      P10       2     Logic        High=동작 / Low=슬립               │
 *  │ DIR         P10       4     Logic                                          │
 *  │ nFAULT      P10       5     입력          Low=폴트 (외부 풀업 R6 10k)        │
 *  │ M0          P8        0     Tri-level                                      │
 *  │ STL_REP     P0        1     입출력        오픈드레인, High=스톨 (풀업 R61)    │
 *  │ M1          P0        2     Quad-level                                     │
 *  │ STL_MODE    P0        3     Quad-level                                     │
 *  │ VREF        P9        1     Logic        High=전류설정 인가                 │
 *  │ STEP        P9_0 = TAUJ1O1 (하드웨어 타이머 출력)                            │
 *  │ TRQ_CNT     AP0_0 = ADCA0I0 (가상채널 01, 리미트 Table1)                     │
 *  └───────────────────────────────────────────────────────────────────────────┘
 *
 *  ※ ENABLE / M0 / M1 / STL_MODE 는 Hi-Z 상태가 유효한 설정값이다.
 *    Config_PORT 에서 해당 핀들의 내부 풀업/풀다운이 반드시 OFF 여야 한다.
 *    (드라이버 내부 풀업 10.5uA 로 Hi-Z 시 1.8~2.2V 가 형성되어야 하므로)
 ***********************************************************************************************************************/
#ifndef DRV8434A_H
#define DRV8434A_H

#include "Config.h"

/***********************************************************************************************************************
 * 데이터시트 타이밍 상수 (SLOSEC6 Table 5-5 / 6.4)
 * 단위: us. 호출자가 지연 처리에 사용할 것.
 **********************************************************************************************************************/
#define DRV8434A_T_WAKE_US          (1200U)  /* nSLEEP High -> 출력 가능 (max 1.2ms)  */
#define DRV8434A_T_ON_US            (1200U)  /* VM > UVLO   -> 출력 가능 (max 1.2ms)  */
#define DRV8434A_T_EN_US            (1000U)  /* ENABLE 변경 -> 출력 반영 (typ 1ms)    */
#define DRV8434A_T_SLEEP_US         ( 120U)  /* nSLEEP Low  -> 슬립 진입 (typ 120us)  */
#define DRV8434A_T_OL_DETECT_US     (65000U) /* Open Load 검출 시간 (typ 65ms)        */
#define DRV8434A_T_OCP_DEGLITCH_US  (   2U)  /* 과전류 디글리치 (typ 2us)             */
#define DRV8434A_T_OCP_RETRY_US     (4000U)  /* 과전류 자동 재시도 (typ 4ms)          */

/* nSLEEP 폴트 클리어 펄스 : 20 ~ 40us (Table 5-5 tRESET)                            */
/* 120us 를 넘기면 슬립으로 진입하므로 상한을 반드시 지킬 것                            */
#define DRV8434A_T_RESET_MIN_US     (  20U)
#define DRV8434A_T_RESET_MAX_US     (  40U)

/***********************************************************************************************************************
 * 스텝 모드 (SLOSEC6 Table 6-2)
 * 330k-to-GND 를 요구하는 2개 모드(Full step 71%, 1/64)는 현 회로에 해당 저항이
 * 미실장이므로 제외한다.
 **********************************************************************************************************************/
typedef enum
{
    DRV8434A_STEP_FULL = 0U,       /* M0=0     M1=0     : 풀스텝 100% 전류         */
    DRV8434A_STEP_NONCIRC_1_2,     /* M0=1     M1=0     : 비원형 1/2 스텝          */
    DRV8434A_STEP_1_2,             /* M0=Hi-Z  M1=0     : 1/2 스텝                 */
    DRV8434A_STEP_1_4,             /* M0=0     M1=1     : 1/4 스텝                 */
    DRV8434A_STEP_1_8,             /* M0=1     M1=1     : 1/8 스텝  <= 현행 운용값  */
    DRV8434A_STEP_1_16,            /* M0=Hi-Z  M1=1     : 1/16 스텝                */
    DRV8434A_STEP_1_32,            /* M0=0     M1=Hi-Z  : 1/32 스텝                */
    DRV8434A_STEP_1_128,           /* M0=Hi-Z  M1=Hi-Z  : 1/128 스텝               */
    DRV8434A_STEP_1_256            /* M0=1     M1=Hi-Z  : 1/256 스텝               */
} Drv8434a_StepMode_t;

/***********************************************************************************************************************
 * 스톨 검출 모드 (SLOSEC6 Table 6-6)
 * '검출 비활성'(STL_MODE=330k) 은 회로 미지원이므로 제외.
 * 대신 StallReport_Disable() 로 nFAULT 오염만 차단한다.
 **********************************************************************************************************************/
typedef enum
{
    DRV8434A_STALL_TORQUE_COUNT = 0U,  /* STL_MODE=GND  : TRQ_CNT 핀이 토크카운트 전압 출력  */
    DRV8434A_STALL_LEARNING,           /* STL_MODE=Hi-Z : 임계 학습, 결과를 TRQ_CNT 로 출력  */
    DRV8434A_STALL_THRESHOLD           /* STL_MODE=DVDD : TRQ_CNT 핀이 임계 전압 입력        */
} Drv8434a_StallMode_t;

/***********************************************************************************************************************
 * API
 **********************************************************************************************************************/

/* --- 초기화 ------------------------------------------------------------------ */
/* 안전 상태로 진입: 출력 차단 + 슬립 + VREF Off + 스톨보고 차단 + 1/8 스텝        */
void Drv8434a_GpioInit(void);

/* --- 전원 상태 --------------------------------------------------------------- */
void Drv8434a_Wakeup(void);                 /* nSLEEP High. 이후 T_WAKE_US 대기 필요 */
void Drv8434a_Sleep(void);                  /* nSLEEP Low + 부수 핀 정리(암전류)     */

/* --- 출력 제어 (ENABLE 핀 3상태) ------------------------------------------------
 * ※ 구 DRV8889 의 DRVOFF 와 논리가 정반대다.
 *      DRVOFF : High = 차단
 *      ENABLE : Low  = 차단
 * ※ 상태 변경 후 T_EN_US 경과해야 출력에 반영된다.
 * ------------------------------------------------------------------------------ */
void Drv8434a_OFF(void);          /* ENABLE Low  : 출력 차단              */
void Drv8434a_ON(void);           /* ENABLE High : 출력 동작, 토크카운트 x1 */
void Drv8434a_ON_TRQ8X(void);      /* ENABLE Hi-Z : 출력 동작, 토크카운트 x8 */

/* --- 방향 -------------------------------------------------------------------- */
void Drv8434a_DirCW(void);
void Drv8434a_DirCCW(void);

/* --- STEP (TAUJ1 하드웨어 출력) ----------------------------------------------- */
void Drv8434a_StepStart(void);
void Drv8434a_StepStop(void);

/* --- 전류 기준 --------------------------------------------------------------- */
void Drv8434a_VrefOn(void);                 /* P9_1 High : 분압 인가                */
void Drv8434a_VrefOff(void);                /* P9_1 Low  : 전류 0                   */

/* --- 모드 설정 --------------------------------------------------------------- */
void Drv8434a_SetStepMode(Drv8434a_StepMode_t mode);
void Drv8434a_SetStallMode(Drv8434a_StallMode_t mode);

/* --- STL_REP (오픈드레인 공유 라인) -------------------------------------------- */
void Drv8434a_StallReportDisable(void);     /* MCU 가 Low 구동 -> 드라이버 스톨보고 차단 */
void Drv8434a_StallReportEnable(void);      /* 라인 해제 -> 드라이버가 구동, 읽기 가능   */
uint8_t Drv8434a_IsStallReported(void);     /* 1 = 스톨 (STL_REP High)              */

/* --- 폴트 -------------------------------------------------------------------- */
uint8_t Drv8434a_IsFault(void);             /* 1 = 폴트 (nFAULT Low)                */
void Drv8434a_FaultClear(void);             /* nSLEEP 20~40us 펄스. 블로킹.          */

#endif /* DRV8434A_H */